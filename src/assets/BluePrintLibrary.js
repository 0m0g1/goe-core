/**
 * GOE Core — BluePrintLibrary
 *
 * All blueprints use the engine's voxel-unit (VU) coordinate system:
 *   VU = 8 per tile,  1 tile = 2 m  →  1 VU ≈ 0.25 m
 *
 * Blueprints are no longer constrained to a single tile.
 * Coordinates are centred on the tile origin (x=0, z=0) so that
 * WorldRenderer.drawBlueprint(bp, tx, ty, elev) places the object's
 * centre over tile (tx, ty).
 *
 * Real-world scale reference
 *   Person      ~1.75 m → 7 VU tall
 *   Car         ~4.5 × 1.8 × 1.5 m → 18 × 7 × 6 VU
 *   Bus         ~12 × 2.5 × 3.0 m → 48 × 10 × 12 VU
 *   Boeing 737  ~37 × 34 × 12 m  → 148 × 136 × 48 VU
 *   Semi-truck  ~22 × 2.5 × 4.0 m → 88 × 10 × 16 VU
 *   Bench       ~1.5 m long → 6 VU
 *   Post box    ~0.5 m wide → 2 VU
 */

